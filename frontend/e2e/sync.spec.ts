import { createHash, randomBytes } from 'node:crypto'
import { device, expect, test, twoDevices } from './helpers'

test('text typed on one device appears on the other, and URLs are detected', async ({ browser }) => {
  const [a, b] = await twoDevices(browser)
  await expect(b.locator('textarea')).toHaveValue('')
  await a.locator('textarea').fill('hello from A\nhttps://example.com/x')
  await expect(b.locator('textarea')).toHaveValue('hello from A\nhttps://example.com/x')
  await expect(b.getByRole('link', { name: 'https://example.com/x' })).toHaveAttribute('target', '_blank')
  await expect(a.getByText('Saved').first()).toBeVisible()
  await b.reload()
  await expect(b.locator('textarea')).toHaveValue('hello from A\nhttps://example.com/x')
  await b.locator('textarea').fill('reply from B')
  await expect(a.locator('textarea')).toHaveValue('reply from B')
  a.once('dialog', d => d.accept())
  await a.getByText('Clear', { exact: true }).click()
  await expect(b.locator('textarea')).toHaveValue('')
})

